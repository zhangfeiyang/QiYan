// 把 shared/config/ 与 Android 的 strings.xml 编译成小程序能 require 的模块。
//
// 两个产物:
//   miniprogram/generated/product-config.js  跨端产品配置 (难度/段位/能力矩阵/引擎档位)
//   miniprogram/generated/strings.js         中英文文案表, 直接抽自 Android 的 strings.xml
//
// 文案不手抄一遍的原因: 抄一次就多一个会漂的副本。同一个 key 在两端解析出
// 同一句话, 用户在 App 里看到的"业余五段"到小程序里就不会变成"业余六级"。
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const difficulties = JSON.parse(await readFile('shared/config/difficulty-levels.json', 'utf8'));
const features = JSON.parse(await readFile('shared/config/features.json', 'utf8'));
const engineProfile = JSON.parse(await readFile('shared/config/engine-profile.json', 'utf8'));
const levelNotes = JSON.parse(await readFile('shared/config/level-notes.json', 'utf8'));
const userRanks = JSON.parse(await readFile('shared/config/user-ranks.json', 'utf8'));

const payload = JSON.stringify({ difficulties, features, engineProfile, levelNotes, userRanks });
const fingerprint = createHash('sha256').update(payload).digest('hex').slice(0, 16);
const config = { fingerprint, difficulties, features, engineProfile, levelNotes, userRanks };

await mkdir('miniprogram/generated', { recursive: true });
await writeFile(
  'miniprogram/generated/product-config.js',
  `// Generated by tools/sync-shared-config.mjs. Do not edit.\nmodule.exports = ${JSON.stringify(config, null, 2)};\n`
);

// ====== 文案表 ======

/**
 * 解析 strings.xml。
 *
 * 只取 <string>, 不取 <string-array>/<plurals> —— 小程序用不到, 而且它们的
 * 结构不是一句话对一个 key, 混进来只会让下游多一层判空。
 * Android 的转义 (\', \", \n) 在这里还原成真实字符, 因为小程序侧是 JS 字符串,
 * 不再经过 Android 资源编译器那一道。
 */
function parseStrings(xml) {
  const out = {};
  const re = /<string\s+name="([^"]+)"\s*(?:formatted="[^"]*"\s*)?>([\s\S]*?)<\/string>/g;
  let m;
  while ((m = re.exec(xml)) !== null) {
    out[m[1]] = m[2]
      .replace(/\\n/g, '\n')
      .replace(/\\'/g, "'")
      .replace(/\\"/g, '"')
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&quot;/g, '"');
  }
  return out;
}

const en = parseStrings(await readFile('app/src/main/res/values/strings.xml', 'utf8'));
const zh = parseStrings(await readFile('app/src/main/res/values-zh/strings.xml', 'utf8'));

const missingZh = Object.keys(en).filter((key) => !(key in zh));
if (missingZh.length) {
  throw new Error(`values-zh 缺少 ${missingZh.length} 个 key: ${missingZh.slice(0, 5).join(', ')}`);
}

// 小程序独有的文案。key 一律 mp_ 前缀且与 Android 的 key 空间不重叠 ——
// 撞名就说明这句话 App 里其实也有, 应该直接用 Android 的 key 而不是另起一份。
const mpStrings = JSON.parse(await readFile('shared/config/miniprogram-strings.json', 'utf8'));
for (const locale of ['zh', 'en']) {
  for (const key of Object.keys(mpStrings[locale])) {
    if (!key.startsWith('mp_')) throw new Error(`小程序文案 key 必须以 mp_ 开头: ${key}`);
    if (key in en) throw new Error(`小程序文案 ${key} 与 Android strings.xml 撞名, 请直接用 Android 的 key`);
  }
}
const zhKeys = Object.keys(mpStrings.zh).sort().join(',');
const enKeys = Object.keys(mpStrings.en).sort().join(',');
if (zhKeys !== enKeys) throw new Error('小程序文案的中英两份 key 不一致');

await writeFile(
  'miniprogram/generated/strings.js',
  `// Generated by tools/sync-shared-config.mjs from app/src/main/res/values*/strings.xml\n` +
    `// and shared/config/miniprogram-strings.json. Do not edit.\n` +
    `module.exports = ${JSON.stringify({
      en: { ...en, ...mpStrings.en },
      zh: { ...zh, ...mpStrings.zh },
    }, null, 2)};\n`
);

// ====== 图标 ======
// 小程序不认 Android 的 VectorDrawable, 但两端的图标必须是同一套 —— 一边是
// Material 的旗子, 另一边随手找个 emoji, 用户一看就知道是两个产品。这里把
// drawable/ic_*.xml 里的 pathData 抽出来, 小程序侧用同样的 24x24 viewBox
// 渲染成内联 SVG。
const iconFiles = (await readdir('app/src/main/res/drawable'))
  .filter((name) => name.startsWith('ic_') && name.endsWith('.xml'));

const icons = {};
for (const file of iconFiles) {
  const xml = await readFile(`app/src/main/res/drawable/${file}`, 'utf8');
  const paths = [...xml.matchAll(/android:pathData="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length) icons[file.replace(/^ic_|\.xml$/g, '')] = paths;
}

await writeFile(
  'miniprogram/generated/icons.js',
  `// Generated by tools/sync-shared-config.mjs from app/src/main/res/drawable/ic_*.xml. Do not edit.\n` +
    `module.exports = ${JSON.stringify(icons, null, 2)};\n`
);

console.log(`shared config synced: ${fingerprint}`);
console.log(`strings synced: ${Object.keys(en).length} keys x 2 locales`);
console.log(`icons synced: ${Object.keys(icons).length}`);
