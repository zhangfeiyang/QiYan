import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const difficulties = JSON.parse(await readFile('shared/config/difficulty-levels.json', 'utf8'));
const features = JSON.parse(await readFile('shared/config/features.json', 'utf8'));
const payload = JSON.stringify({ difficulties, features });
const fingerprint = createHash('sha256').update(payload).digest('hex').slice(0, 16);
const output = `// Generated by tools/sync-shared-config.mjs. Do not edit.\nmodule.exports = ${JSON.stringify({ fingerprint, difficulties, features }, null, 2)};\n`;
await mkdir('miniprogram/generated', { recursive: true });
await writeFile('miniprogram/generated/product-config.js', output);
console.log(`shared config synced: ${fingerprint}`);
